/* secp256k1 constants and fixed-base comb table.
   AUTO-GENERATED by tools/gen/gen_secp_tables.py -- do not edit.
   Verified at generation time: G on curve, order(G)==N, P/N prime,
   comb table reproduces k*G. */
#ifndef OW_SECP_TABLES_H
#define OW_SECP_TABLES_H
#include <stdint.h>

extern const uint8_t SECP_P[32];
extern const uint8_t SECP_N[32];
extern const uint8_t SECP_GX[32];
extern const uint8_t SECP_GY[32];

#define SECP_COMB_TEETH   8
#define SECP_COMB_SPACING 32
#define SECP_COMB_BANK    2

/* SECP_COMB[(m-1)*64] = affine (x||y), 32 bytes each, little-endian,
   of sum_{j in bits(m)} 2^(32j)*G, for m = 1..255. Lives in bank 2. */
extern const uint8_t SECP_COMB[16320];

/* The table lives in a switchable ROM bank; all crypto code lives in
   bank 0, which stays mapped, so switching here is safe. */
#ifdef OW_GAMEBOY
#include <gb/gb.h>
static const uint8_t *secp_comb_ptr(uint16_t off)
{
    SWITCH_ROM(SECP_COMB_BANK);
    return &SECP_COMB[off];
}
#else
static const uint8_t *secp_comb_ptr(uint16_t off)
{
    return &SECP_COMB[off];
}
#endif
#define SECP_COMB_PTR(off) secp_comb_ptr(off)

#endif
