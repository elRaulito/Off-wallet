"""SHA-512 constants as little-endian byte arrays.

Derived from first principles: K[i] is the fractional part of the cube root of
the i-th prime, H0[i] that of the square root, both to 64 bits. Stored
little-endian (byte 0 = least significant) because that is the order the
byte-wise adder walks.
"""
import io, math

def icbrt(n):
    x = int(round(n ** (1 / 3)))
    while x * x * x > n: x -= 1
    while (x + 1) ** 3 <= n: x += 1
    return x

def cbrt_frac(n, bits):
    return icbrt(n << (3 * bits)) - (icbrt(n) << bits)

def sqrt_frac(n, bits):
    return math.isqrt(n << (2 * bits)) - (math.isqrt(n) << bits)

primes = []
n = 2
while len(primes) < 80:
    if all(n % p for p in primes if p * p <= n):
        primes.append(n)
    n += 1

K = [cbrt_frac(p, 64) for p in primes[:80]]
H0 = [sqrt_frac(p, 64) for p in primes[:8]]
assert K[0] == 0x428a2f98d728ae22, hex(K[0])
assert K[79] == 0x6c44198c4a475817, hex(K[79])
assert H0[0] == 0x6a09e667f3bcc908, hex(H0[0])
print('verified: K[0], K[79] and H0[0] match the published SHA-512 constants')

def le(v):
    return ','.join('0x%02x' % ((v >> (8 * i)) & 0xff) for i in range(8))

out = ['/* SHA-512 constants, little-endian bytes.',
       '   AUTO-GENERATED by tools/gen/gen_sha512_tables.py from frac(cbrt(p))',
       '   and frac(sqrt(p)) -- not transcribed. */',
       '#ifndef OW_SHA512_TABLES_H',
       '#define OW_SHA512_TABLES_H',
       '#include <stdint.h>',
       '',
       'static const uint8_t SHA512_K[80][8] = {']
for i, v in enumerate(K):
    out.append('  {%s},' % le(v))
out.append('};')
out.append('')
out.append('static const uint8_t SHA512_H0[8][8] = {')
for v in H0:
    out.append('  {%s},' % le(v))
out.append('};')
out.append('')
out.append('#endif')
io.open('../../src/crypto/sha512_tables.h', 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote src/crypto/sha512_tables.h (80 round constants + 8 initial words)')
