"""Generate the SHA-512 compression function in SM83 assembly.

Why generate rather than hand-write: the useful parts are mechanical (eight
unrolled bytes per primitive, one rotation routine per shift amount, the round
body), and keeping the loops in Python means the assembly stays consistent when
a detail changes.

Measured in C on hardware: 1001 ms per compression, which puts the BIP-39 hatch
at 71 minutes. Nearly all of that is SDCC emitting a pointer-indexed load, an
add and a store for every byte of every 64-bit word.

Three ideas make the assembly version much cheaper:

  * Words are stored TWICE, back to back (16 bytes for a 64-bit value). A
    rotation by 8q+r then reads eight consecutive bytes starting at offset q --
    no wrap-around test, no masking, HL just walks forward.
  * The working variables a..h are not copied at the end of a round. They live
    in eight slots and the round only writes two of them: d+T1 (which becomes
    the next e) and T1+T2 (which becomes the next a). Rotating a base index
    instead of the data removes six 8-byte copies per round.
  * Every primitive is unrolled over its eight bytes, with the carry flowing
    between them: `ld a,(de) / adc a,(hl) / ld (hl+),a / inc de` is eight
    machine cycles per byte, and `inc de` leaves the carry alone.

The round body computes its addresses at run time from the rotating base. That
costs about 2% and keeps the generated code at one round instead of sixteen
unrolled copies.
"""
import io, math, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(ROOT, 'src', 'crypto', 'sha512_sm83.s')

L = []


def e(line=''):
    L.append(line)


# --------------------------------------------------------------- constants
def icbrt(n):
    x = int(round(n ** (1 / 3)))
    while x * x * x > n: x -= 1
    while (x + 1) ** 3 <= n: x += 1
    return x


def cbrt_frac(n, bits):
    return icbrt(n << (3 * bits)) - (icbrt(n) << bits)


primes = []
n = 2
while len(primes) < 80:
    if all(n % p for p in primes if p * p <= n):
        primes.append(n)
    n += 1
K = [cbrt_frac(p, 64) for p in primes[:80]]
assert K[0] == 0x428a2f98d728ae22 and K[79] == 0x6c44198c4a475817

# --------------------------------------------------------------- preamble
e(';; SHA-512 compression for SM83, generated by tools/gen/gen_sha512_asm.py.')
e(';; Do not edit: change the generator.')
e(';;')
e(';; Layout: every 64-bit value is eight little-endian bytes. The working')
e(';; slots and the message schedule are stored twice in a row (16 bytes) so')
e(';; that a rotation can read eight consecutive bytes at any byte offset.')
e()
e('        .module sha512_sm83')
e('        .globl  _sha512_block_asm, _sha_h, _sha_src')
e('        .globl  _sha_v, _sha_w   ; exported so tests can inspect them')
e('        .globl  _sha_t1, _sha_s0, _sha_s1, _sha_x')
e('        .globl  _sha_rounds      ; defined in sha512.c so it can be initialised')
e()
e('        .area   _DATA')
e('_sha_h::')
e('        .ds     2               ; pointer to ctx->h (8 words, NOT doubled)')
e('_sha_src::')
e('        .ds     2               ; pointer to the 128-byte input block')
e('_sha_v::')
e('        .ds     128             ; a..h, eight slots of 16 (doubled)')
e('_sha_w::')
e('        .ds     256             ; W[0..15], sixteen slots of 16 (doubled)')
e('_sha_t1::')
e('        .ds     8')
e('sha_t2:')
e('        .ds     8')
e('_sha_s0::')
e('        .ds     8')
e('_sha_s1::')
e('        .ds     8')
e('sha_tm:')
e('        .ds     8')
e('_sha_x::')
e('        .ds     8               ; Ch / Maj scratch')
e('sha_base:')
e('        .ds     1               ; which slot currently holds a')
e('sha_i:')
e('        .ds     1               ; round number')

e()
e('        .area   _CODE_4')
e()

# ------------------------------------------------------------- primitives
e(';; HL = dst, DE = src : dst += src   (8 bytes, carry chained)')
e('sha_add8:')
e('        xor     a               ; clears the carry')
for i in range(8):
    e('        ld      a,(de)')
    e('        adc     a,(hl)')
    e('        ld      (hl+),a')
    e('        inc     de')
e('        ret')
e()

e(';; HL = dst, DE = src : dst ^= src')
e('sha_xor8:')
for i in range(8):
    e('        ld      a,(de)')
    e('        xor     (hl)')
    e('        ld      (hl+),a')
    e('        inc     de')
e('        ret')
e()

e(';; HL = dst, DE = src : dst &= src')
e('sha_and8:')
for i in range(8):
    e('        ld      a,(de)')
    e('        and     (hl)')
    e('        ld      (hl+),a')
    e('        inc     de')
e('        ret')
e()

e(';; HL = dst, DE = src : dst = src')
e('sha_cpy8:')
for i in range(8):
    e('        ld      a,(de)')
    e('        ld      (hl+),a')
    e('        inc     de')
e('        ret')
e()

e(';; HL = base of a doubled word : copy bytes 0..7 over bytes 8..15')
e('sha_mir8:')
e('        ld      d,h')
e('        ld      e,l             ; DE = base')
e('        ld      a,l')
e('        add     a,#8')
e('        ld      l,a')
e('        ld      a,h')
e('        adc     a,#0')
e('        ld      h,a             ; HL = base + 8')
for i in range(8):
    e('        ld      a,(de)')
    e('        ld      (hl+),a')
    e('        inc     de')
e('        ret')
e()

# --------------------------------------------------------------- rotations
# rot_rN: HL = source (doubled word, already offset by q), DE = destination.
# Reads nine bytes; writes eight. dst[i] = (src[i] >> N) | (src[i+1] << (8-N)).
for N in range(8):
    e(';; HL = src+q, DE = dst : dst = 64-bit value at HL rotated right %d bits' % N)
    e('sha_rot%d:' % N)
    if N == 0:
        for i in range(8):
            e('        ld      a,(hl+)')
            e('        ld      (de),a')
            e('        inc     de')
    else:
        for i in range(8):
            e('        ld      a,(hl+)         ; cur')
            e('        ld      c,a')
            e('        ld      a,(hl)          ; next')
            for _ in range(N):
                e('        srl     a')
                e('        rr      c')
            e('        ld      a,c')
            e('        ld      (de),a')
            e('        inc     de')
    e('        ret')
    e()

# shr_rN: logical shift right, so nothing wraps into the top byte.
for N in (6, 7):
    e(';; HL = src, DE = dst : dst = value at HL shifted right %d bits' % N)
    e('sha_shr%d:' % N)
    for i in range(8):
        e('        ld      a,(hl+)         ; cur')
        e('        ld      c,a')
        if i == 7:
            e('        xor     a               ; nothing above the top byte')
        else:
            e('        ld      a,(hl)          ; next')
        for _ in range(N):
            e('        srl     a')
            e('        rr      c')
        e('        ld      a,c')
        e('        ld      (de),a')
        e('        inc     de')
    e('        ret')
    e()

# ------------------------------------------------------- address helpers
e(';; A = slot index 0..7 : HL = sha_v + A*16')
e('sha_vaddr:')
e('        and     #7')
e('        swap    a               ; *16, safe because A <= 7')
e('        ld      l,a')
e('        ld      h,#0')
e('        ld      de,#_sha_v')
e('        add     hl,de')
e('        ret')
e()
e(';; A = word index 0..15 : HL = sha_w + A*16')
e('sha_waddr:')
e('        and     #15')
e('        swap    a               ; *16, safe because A <= 15')
e('        ld      l,a')
e('        ld      h,#0')
e('        ld      de,#_sha_w')
e('        add     hl,de')
e('        ret')
e()
e(';; A = k : HL = sha_v + ((base + k) & 7) * 16')
e('sha_slot:')
e('        ld      hl,#sha_base')
e('        add     a,(hl)')
e('        jp      sha_vaddr')
e()

# ------------------------------------------------------------- K table
e(';; the eighty round constants, little-endian')
e('sha_k:')
for v in K:
    e('        .db     ' + ','.join('#0x%02x' % ((v >> (8 * i)) & 0xff)
                                    for i in range(8)))
e()

e(';; A = round number : HL = sha_k + A*8')
e('sha_kaddr:')
e('        ld      h,#0')
e('        ld      l,a')
e('        add     hl,hl')
e('        add     hl,hl')
e('        add     hl,hl           ; *8')
e('        ld      de,#sha_k')
e('        add     hl,de')
e('        ret')
e()


# ---------------------------------------------------------- code emitters
def call2(dst_setup, src_setup, fn):
    """For add8/xor8/and8/cpy8/mir8: HL = dst, DE = src."""
    for ln in src_setup:
        e(ln)
    e('        push    hl')
    for ln in dst_setup:
        e(ln)
    e('        pop     de')
    e('        call    ' + fn)


def call_rot(dst_setup, src_setup, fn):
    """For the rotation and shift routines, which read through HL and write
    through DE -- the opposite way round from the other primitives."""
    for ln in dst_setup:
        e(ln)
    e('        push    hl')
    for ln in src_setup:
        e(ln)
    e('        pop     de')
    e('        call    ' + fn)


def const(addr):
    return ['        ld      hl,#' + addr]


def slot(k, off=0):
    """Address of working slot k (a=0..h=7), plus a byte offset."""
    out = ['        ld      a,#%d' % k, '        call    sha_slot']
    if off:
        out += ['        ld      a,l', '        add     a,#%d' % off,
                '        ld      l,a', '        ld      a,h',
                '        adc     a,#0', '        ld      h,a']
    return out


def word(expr, off=0):
    """Address of W[(i + expr) & 15], plus a byte offset."""
    out = ['        ld      a,(sha_i)']
    if expr:
        out += ['        add     a,#%d' % expr]
    out += ['        call    sha_waddr']
    if off:
        out += ['        ld      a,l', '        add     a,#%d' % off,
                '        ld      l,a', '        ld      a,h',
                '        adc     a,#0', '        ld      h,a']
    return out


def ldbc(sym):
    """BC = the 16-bit pointer stored at `sym`. SM83 has no "ld bc,(nn)"."""
    return ['        ld      a,(#%s)' % sym,
            '        ld      c,a',
            '        ld      a,(#%s+1)' % sym,
            '        ld      b,a']


def kaddr():
    return ['        ld      a,(sha_i)', '        call    sha_kaddr']


# --------------------------------------------------------------- the block
e(';; ------------------------------------------------------------- block')
e(';; void sha512_block_asm(void): hashes the 128 bytes at _sha_src into the')
e(';; eight words at _sha_h.')
e('_sha512_block_asm::')
e('        push    bc')
e()
e(';; W[i] = the i-th big-endian word of the input, then mirrored')
e('        xor     a')
e('        ld      (sha_i),a')
e('wload:')
e('        ld      a,(sha_i)')
e('        call    sha_waddr')
e('        ld      d,h')
e('        ld      e,l             ; DE = &W[i]')
e('        ld      a,(sha_i)')
e('        ld      h,#0')
e('        ld      l,a')
e('        add     hl,hl')
e('        add     hl,hl')
e('        add     hl,hl           ; i*8')
for _ln in ldbc('_sha_src'): e(_ln)
e('        add     hl,bc')
e('        ld      bc,#7')
e('        add     hl,bc           ; HL = src + i*8 + 7, the low byte first')
for i in range(8):
    e('        ld      a,(hl-)')
    e('        ld      (de),a')
    e('        inc     de')
e('        ld      a,(sha_i)')
e('        call    sha_waddr')
e('        call    sha_mir8')
e('        ld      hl,#sha_i')
e('        inc     (hl)')
e('        ld      a,(hl)')
e('        cp      #16')
e('        jr      nz,wload')
e()
e(';; v[k] = h[k], doubled')
e('        xor     a')
e('        ld      (sha_i),a')
e('vload:')
e('        ld      a,(sha_i)')
e('        call    sha_vaddr')
e('        push    hl')
e('        ld      a,(sha_i)')
e('        ld      h,#0')
e('        ld      l,a')
e('        add     hl,hl')
e('        add     hl,hl')
e('        add     hl,hl           ; k*8')
for _ln in ldbc('_sha_h'): e(_ln)
e('        add     hl,bc')
e('        ld      d,h')
e('        ld      e,l')
e('        pop     hl')
e('        call    sha_cpy8')
e('        ld      a,(sha_i)')
e('        call    sha_vaddr')
e('        call    sha_mir8')
e('        ld      hl,#sha_i')
e('        inc     (hl)')
e('        ld      a,(hl)')
e('        cp      #8')
e('        jr      nz,vload')
e()
e('        xor     a')
e('        ld      (sha_base),a')
e('        ld      (sha_i),a')
e()
e('round:')
e('        ld      a,(sha_i)')
e('        cp      #16')
e('        jp      c,no_sched')
e()
e(';; ---- message schedule: W[j] += sigma0(W[j+1]) + W[j+9] + sigma1(W[j+14])')
e(';; sigma0(x) = rotr1(x) ^ rotr8(x) ^ shr7(x)')
call_rot(const('_sha_s0'), word(1), 'sha_rot1')
call_rot(const('sha_tm'), word(1, off=1), 'sha_rot0')
call2(const('_sha_s0'), const('sha_tm'), 'sha_xor8')
call_rot(const('sha_tm'), word(1), 'sha_shr7')
call2(const('_sha_s0'), const('sha_tm'), 'sha_xor8')
e(';; sigma1(y) = rotr19(y) ^ rotr61(y) ^ shr6(y)')
call_rot(const('_sha_s1'), word(14, off=2), 'sha_rot3')
call_rot(const('sha_tm'), word(14, off=7), 'sha_rot5')
call2(const('_sha_s1'), const('sha_tm'), 'sha_xor8')
call_rot(const('sha_tm'), word(14), 'sha_shr6')
call2(const('_sha_s1'), const('sha_tm'), 'sha_xor8')
e(';; W[j] += s0 + W[j+9] + s1, then refresh the mirrored copy')
call2(word(0), const('_sha_s0'), 'sha_add8')
call2(word(0), word(9), 'sha_add8')
call2(word(0), const('_sha_s1'), 'sha_add8')
for ln in word(0):
    e(ln)
e('        call    sha_mir8')
e()
e('no_sched:')
e(';; ---- Sum1(e) = rotr14 ^ rotr18 ^ rotr41,  e = slot 4')
call_rot(const('_sha_s1'), slot(4, off=1), 'sha_rot6')
call_rot(const('sha_tm'), slot(4, off=2), 'sha_rot2')
call2(const('_sha_s1'), const('sha_tm'), 'sha_xor8')
call_rot(const('sha_tm'), slot(4, off=5), 'sha_rot1')
call2(const('_sha_s1'), const('sha_tm'), 'sha_xor8')
e()
e(';; ---- Ch(e,f,g) = g ^ (e & (f ^ g))')
call2(const('_sha_x'), slot(5), 'sha_cpy8')
call2(const('_sha_x'), slot(6), 'sha_xor8')
call2(const('_sha_x'), slot(4), 'sha_and8')
call2(const('_sha_x'), slot(6), 'sha_xor8')
e()
e(';; ---- T1 = h + Sum1 + Ch + K[i] + W[j]')
call2(const('_sha_t1'), slot(7), 'sha_cpy8')
call2(const('_sha_t1'), const('_sha_s1'), 'sha_add8')
call2(const('_sha_t1'), const('_sha_x'), 'sha_add8')
call2(const('_sha_t1'), kaddr(), 'sha_add8')
call2(const('_sha_t1'), word(0), 'sha_add8')
e()
e(';; ---- Sum0(a) = rotr28 ^ rotr34 ^ rotr39,  a = slot 0')
call_rot(const('_sha_s0'), slot(0, off=3), 'sha_rot4')
call_rot(const('sha_tm'), slot(0, off=4), 'sha_rot2')
call2(const('_sha_s0'), const('sha_tm'), 'sha_xor8')
call_rot(const('sha_tm'), slot(0, off=4), 'sha_rot7')
call2(const('_sha_s0'), const('sha_tm'), 'sha_xor8')
e()
e(';; ---- Maj(a,b,c) = ((a ^ b) & (b ^ c)) ^ b')
call2(const('_sha_x'), slot(0), 'sha_cpy8')
call2(const('_sha_x'), slot(1), 'sha_xor8')
call2(const('sha_tm'), slot(1), 'sha_cpy8')
call2(const('sha_tm'), slot(2), 'sha_xor8')
call2(const('_sha_x'), const('sha_tm'), 'sha_and8')
call2(const('_sha_x'), slot(1), 'sha_xor8')
e()
e(';; ---- T2 = Sum0 + Maj, kept in sha_s0')
call2(const('_sha_s0'), const('_sha_x'), 'sha_add8')
e()
e(';; ---- the only two writes: d += T1 becomes the next e ...')
call2(slot(3), const('_sha_t1'), 'sha_add8')
for ln in slot(3):
    e(ln)
e('        call    sha_mir8')
e(';; ... and T1 + T2 lands in h\'s slot, becoming the next a')
call2(slot(7), const('_sha_t1'), 'sha_cpy8')
call2(slot(7), const('_sha_s0'), 'sha_add8')
for ln in slot(7):
    e(ln)
e('        call    sha_mir8')
e()
e(';; rotate the slots: a moves one place back')
e('        ld      hl,#sha_base')
e('        ld      a,(hl)')
e('        dec     a')
e('        and     #7')
e('        ld      (hl),a')
e()
e('        ld      hl,#sha_i')
e('        inc     (hl)')
e('        ld      a,(hl)')
e('        ld      hl,#_sha_rounds')
e('        cp      (hl)')
e('        jp      nz,round')
e()
e(';; h[k] += v[(base + k) & 7]')
e('        xor     a')
e('        ld      (sha_i),a')
e('hstore:')
e('        ld      a,(sha_i)')
e('        ld      h,#0')
e('        ld      l,a')
e('        add     hl,hl')
e('        add     hl,hl')
e('        add     hl,hl           ; k*8')
for _ln in ldbc('_sha_h'): e(_ln)
e('        add     hl,bc           ; HL = &h[k]')
e('        push    hl')
e('        ld      a,(sha_i)')
e('        call    sha_slot        ; DE = &v[(base+k)&7]')
e('        ld      d,h')
e('        ld      e,l')
e('        pop     hl')
e('        call    sha_add8')
e('        ld      hl,#sha_i')
e('        inc     (hl)')
e('        ld      a,(hl)')
e('        cp      #8')
e('        jr      nz,hstore')
e()
e('        pop     bc')
e('        ret')

io.open(OUT, 'w', newline='\n').write('\n'.join(L) + '\n')
code = sum(1 for x in L if x.strip() and not x.strip().startswith(';'))
print('wrote %s' % os.path.relpath(OUT, ROOT))
print('  %d assembly lines (%d instructions), K table included' % (len(L), code))
